#!/usr/bin/env node
/**
 * Writes supabase-config.js (loaded by index.html) from environment variables.
 *
 * The site is static (no bundler), so a .env file cannot be read by the browser.
 * This script bridges the gap using the same variable names you would use with Vite:
 *
 *   VITE_SUPABASE_URL        e.g. https://abcdxyz.supabase.co
 *   VITE_SUPABASE_ANON_KEY   the anon / publishable key  (NEVER the service_role / secret key)
 *
 * Local use : put them in .env, then run  node scripts/generate-config.js
 * Netlify   : add them under Site settings -> Environment variables; netlify.toml runs this on every deploy.
 *
 * The anon/publishable key is designed to be public: Row Level Security protects the data.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');

function readDotEnv(file) {
  const out = {};
  if (!fs.existsSync(file)) return out;
  for (const raw of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq < 1) continue;
    let val = line.slice(eq + 1).trim();
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) val = val.slice(1, -1);
    out[line.slice(0, eq).trim()] = val;
  }
  return out;
}

const env = Object.assign({}, readDotEnv(path.join(root, '.env')), process.env);
const url = (env.VITE_SUPABASE_URL || env.SUPABASE_URL || '').trim();
const key = (env.VITE_SUPABASE_ANON_KEY || env.SUPABASE_ANON_KEY || '').trim();

function fatal(msg) { console.error('generate-config: ' + msg); process.exit(1); }

// Safety: never ship a secret key to the browser.
if (key.startsWith('sb_secret_')) fatal('refusing to use a secret key. Use the publishable / anon key.');
if (key.split('.').length === 3) {
  try {
    const payload = JSON.parse(Buffer.from(key.split('.')[1].replace(/-/g, '+').replace(/_/g, '/'), 'base64').toString('utf8'));
    if (payload.role === 'service_role') fatal('that is the service_role key. It bypasses all security. Use the anon key.');
  } catch (e) { /* not a decodable JWT: continue */ }
}
if (url && !/^https:\/\/[a-z0-9-]+\.supabase\.(co|in)\/?$/i.test(url)) {
  console.warn('generate-config: warning: URL does not look like https://<project>.supabase.co');
}

if (!url || !key) {
  console.warn('generate-config: VITE_SUPABASE_URL / VITE_SUPABASE_ANON_KEY not set. The app will show a "Setup needed" screen.');
}

const body =
  '/* generated by scripts/generate-config.js - do not edit, do not commit */\n' +
  'window.IDARAH_SUPABASE = ' + JSON.stringify({ url: url.replace(/\/$/, ''), anonKey: key }) + ';\n';
fs.writeFileSync(path.join(root, 'supabase-config.js'), body);
console.log('generate-config: wrote supabase-config.js (' + (url && key ? 'configured' : 'EMPTY') + ')');
